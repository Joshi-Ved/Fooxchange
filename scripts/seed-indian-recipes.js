async function main() {
    console.log(`🌱 Starting to seed ${indianRecipes.length} Indian recipes...\n`);

    try {
        // Create test user
        const user = await prisma.user.upsert({
            where: { clerkId: "indian_recipes_seed" },
            update: {},
            create: {
                clerkId: "indian_recipes_seed",
                email: "recipes@fooxchange.com",
                name: "Indian Cuisine Collection",
                avatarUrl: null,
                bio: "Authentic Indian recipes from across the subcontinent",
            },
        });

        console.log("✅ Created recipe curator:", user.name);

        // Process each recipe
        let successCount = 0;
        let errorCount = 0;

        for (const [index, recipeData] of indianRecipes.entries()) {
            try {
                // Create ingredient records first
                const ingredientRecords = await Promise.all(
                    recipeData.ingredients.map(async (ing) => {
                        const slug = ing.name
                            .toLowerCase()
                            .replace(/[^a-z0-9]+/g, "-")
                            .replace(/^-|-$/g, "");

                        return prisma.ingredient.upsert({
                            where: { slug },
                            update: {},
                            create: {
                                name: ing.name,
                                slug,
                                category: "Other",
                            },
                        });
                    })
                );

                // Create recipe
                await prisma.recipe.create({
                    data: {
                        title: recipeData.title,
                        description: recipeData.description,
                        imageUrl: null,
                        prepTime: recipeData.prepTime,
                        cookTime: recipeData.cookTime,
                        servings: recipeData.servings,
                        difficulty: recipeData.difficulty,
                        authorId: user.id,
                        ingredients: {
                            create: ingredientRecords.map((ing, idx) => ({
                                amount: recipeData.ingredients[idx].amount,
                                isOptional: false,
                                ingredientId: ing.id,
                            })),
                        },
                        steps: {
                            create: recipeData.steps.map((step, idx) => ({
                                order: idx + 1,
                                content: step,
                                imageUrl: null,
                            })),
                        },
                    },
                });

                successCount++;
                if ((index + 1) % 10 === 0) {
                    console.log(`   Progress: ${index + 1}/150 recipes...`);
                }
            } catch (error) {
                errorCount++;
                console.error(`❌ Failed to create "${recipeData.title}":`, error.message);
            }
        }

        console.log("\n" + "=".repeat(60));
        console.log(`✅ Successfully created: ${successCount} recipes`);
        if (errorCount > 0) {
            console.log(`❌ Failed: ${errorCount} recipes`);
        }
        console.log("=".repeat(60));
        console.log("\n🎉 Indian recipes seeding complete!");
    } catch (error) {
        console.error("❌ Seeding failed:", error);
        throw error;
    } finally {
        await prisma.$disconnect();
    }
}

main()
    .catch((e) => {
        console.error(e);
        process.exit(1);
    });
